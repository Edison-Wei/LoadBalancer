def request(port, path='/request', method='GET', request_id=None):
    connection = http.client.HTTPConnection('127.0.0.1', port, timeout=3)
    try:
        connection.request(method, path, headers={'X-Request-ID': request_id} if request_id else {})
        response = connection.getresponse()
        return response.status, response.read()
    finally:
        connection.close()


def fixture(identifier, port):
    """An owned origin process provides faults unavailable in the C++ simulator."""
    class Handler(http.server.BaseHTTPRequestHandler):
        protocol_version = 'HTTP/1.1'

        def log_message(self, *_):
            pass

        def do_POST(self):
            mode = urllib.parse.parse_qs(urllib.parse.urlsplit(self.path).query).get('value', [''])[0]
            if urllib.parse.urlsplit(self.path).path != '/admin/mode' or mode not in {
                    'normal', 'delay', 'reset', 'unready', 'error', 'flap'}:
                self.respond(400)
                return
            with self.server.lock:
                self.server.mode, self.server.probes = mode, 0
            self.respond(200)

        def respond(self, status):
            body = json.dumps({'server_id': identifier, 'request_id': self.headers.get('X-Request-ID', '')}).encode()
            self.send_response(status)
            self.send_header('Content-Length', str(len(body)))
            self.send_header('Connection', 'close')
            self.end_headers()
            try:
                self.wfile.write(body)
            except (BrokenPipeError, ConnectionResetError):
                pass

        def do_GET(self):
            path = urllib.parse.urlsplit(self.path).path
            with self.server.lock:
                mode = self.server.mode
                if path == '/health':
                    self.server.probes += 1
                    sequence = self.server.probes
            if path == '/health':
                self.respond(503 if mode == 'unready' or mode == 'flap' and sequence % 2 else 200)
                return
            if mode == 'reset':
                self.connection.setsockopt(socket.SOL_SOCKET, socket.SO_LINGER, struct.pack('ii', 1, 0))
                self.connection.close()
                self.close_connection = True
                return
            if mode == 'delay':
                time.sleep(0.7)
            else:
                time.sleep(0.02)
            self.respond(500 if mode == 'error' else 200)

    class Server(http.server.ThreadingHTTPServer):
        daemon_threads = True
        allow_reuse_address = True

    server = Server(('127.0.0.1', port), Handler)
    server.lock, server.mode, server.probes = threading.Lock(), 'normal', 0
    signal.signal(signal.SIGTERM, lambda *_: sys.exit(0))
    print(json.dumps({'event': 'listening', 'port': server.server_port, 'server_id': identifier}), flush=True)
    try:
        server.serve_forever(poll_interval=0.02)
    finally:
        server.server_close()


def make_plan(seed):
    rng = random.Random(seed)
    names = list('ABC')
    return {'schema': 1, 'seed': seed, 'workers': 4, 'path': '/slow?ms=20',
            'single_crash': rng.choice(names), 'multi_crash': rng.sample(names, 2),
            'all_crash': rng.sample(names, 3),
            'restarts': [rng.choice(names) for _ in range(3)],
            'fault_order': rng.sample(['delay', 'reset', 'error'], 3)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--backend')
    parser.add_argument('--proxy')
    parser.add_argument('--logs', type=Path)
    parser.add_argument('--seed', type=int, default=7)
    parser.add_argument('--replay', type=Path, help='Replay the stored plan from a report, including failed runs')
    parser.add_argument('--fixture', action='store_true')
    parser.add_argument('--id', default='C')
    parser.add_argument('--port', type=int, default=0)
    args = parser.parse_args()
    if args.fixture:
        fixture(args.id, args.port)
        return
    if not args.backend or not args.proxy or not args.logs:
        parser.error('--backend, --proxy, and --logs are required')
    plan = json.loads(args.replay.read_text())['plan'] if args.replay else make_plan(args.seed)
    # Replay accepts only plans generated by this schema, never arbitrary commands.
    check(plan == make_plan(plan['seed']), 'Replay plan differs from supported deterministic schema')
    check(0 <= plan['seed'] <= 0xffffffff, 'Seed must be uint32')
    if args.replay:
        check(args.logs.resolve() != args.replay.resolve().parent, 'Replay must use a new output directory')
    args.logs.mkdir(parents=True, exist_ok=True)
    started = time.monotonic()
    lock, stop = threading.Lock(), threading.Event()
    records, stream, owned, exits, windows, observations, metrics = [], [], [], [], [], [], []
    active, ports, generation = {}, {}, Counter()
    planned_exits = {}
    threads = []
    balancer = None
    report = {'plan': plan, 'plan_sha256': hashlib.sha256(json.dumps(plan, sort_keys=True).encode()).hexdigest(),
              'python_version': sys.version, 'backend_binary': str(Path(args.backend).resolve()),
              'proxy_binary': str(Path(args.proxy).resolve()),
              'passed': False, 'checks': [], 'windows': windows, 'observations': observations, 'process_exits': exits}
    event_file = (args.logs / 'events.jsonl').open('w')
    # A timeout/interruption still leaves a seed and replayable plan on disk.
    (args.logs / 'report.json').write_text(json.dumps(report, indent=2) + '\n')

    interruption_requested = [False]
    def interrupted(*_):
        # Raise only at a wait barrier, never halfway through child bookkeeping.
        interruption_requested[0] = True
    signal.signal(signal.SIGTERM, interrupted)

    def now():
        return time.monotonic() - started

    def event(kind, **fields):
        row = {'event': kind, 'elapsed_seconds': now(), 'timestamp_ms': time.time_ns() // 1000000,
               'seed': plan['seed'], **fields}
        stream.append(row)
        event_file.write(json.dumps(row) + '\n')
        event_file.flush()
        return row

    def start(executable, flags, label):
        child = OwnedProcess(executable, flags, label, args.logs)
        owned.append(child)
        port = child.ready()
        event('process_started', name=label, pid=child.process.pid, port=port)
        return child, port

    def start_backend(name):
        generation[name] += 1
        port = ports.get(name, 0)
        if name == 'C':
            child, port = start(sys.executable, [str(Path(__file__).resolve()), '--fixture', '--id', name,
                                               '--port', str(port)], f'{name}-{generation[name]}')
        else:
            child, port = start(args.backend, ['--id', name, '--port', str(port), '--test-mode'],
                                f'{name}-{generation[name]}')
        active[name], ports[name] = child, port

    def reap(child, expected, reason):
        code = child.process.wait(timeout=5)
        child.stderr.close()
        child.process.stdout.close()
        owned.remove(child)
        planned_exits.pop(child, None)
        exits.append({'pid': child.process.pid, 'code': code, 'expected': expected, 'reason': reason})
        event('process_exited', pid=child.process.pid, code=code, expected=expected, reason=reason)
        check(code == expected, f'Unexpected child exit {code}, expected {expected}: {child.path}')

    def scrape(label):
        check(balancer.process.poll() is None, 'Load balancer crashed')
        status, body = request(balancer.event['metrics_port'], '/metrics')
        check(status == 200, 'Metrics scrape failed')
        text = body.decode()
        samples = parse(text)
        metrics.append({'label': label, 'elapsed_seconds': now(), 'text': text})
        return samples

    def wait(predicate, description, timeout=10):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if interruption_requested[0]:
                raise InterruptedError('Chaos harness received SIGTERM')
            result = predicate()
            if result:
                return result
            check(balancer.process.poll() is None, 'Load balancer crashed while ' + description)
            time.sleep(0.01)
        raise AssertionError(description)

    def health(names, target):
        samples = scrape('health_poll')
        return all(value(samples, 'lb_backend_healthy', backend=name) == target for name in names)

    def transition(name, target, injected):
        # Probe/state timestamps originate in the LB, separate from injection
        # timestamps and this harness's observation time.
        probe = wait(lambda: next((row for row in events(balancer)
                                  if row.get('event') == 'health_probe' and row.get('backend') == name
                                  and row.get('timestamp_ms', 0) >= injected['timestamp_ms']
                                  and (row.get('reason') == 'success') == (target == 'HEALTHY')), None),
                     f'{name} probe observation {target}')
        change = wait(lambda: next((row for row in events(balancer)
                                   if row.get('event') == 'health_transition' and row.get('backend') == name
                                   and row.get('to') == target and row.get('timestamp_ms', 0) >= injected['timestamp_ms']), None),
                      f'{name} transition {target}')
        duration = (change['timestamp_ms'] - injected['timestamp_ms']) / 1000
        check(0 <= duration < 5, f'{name} health detection/recovery exceeded bound')
        row = {'backend': name, 'to': target, 'injected': injected,
               'first_observed_probe': probe, 'health_transition': change,
               'harness_observed_seconds': now(), 'transition_delay_seconds': duration}
        observations.append(row)
        event('transition_observed', backend=name, to=target, transition_delay_seconds=duration)

    def window(label, allowed={200}, excluded=(), minimum=16):
        began = now()
        def selected():
            with lock:
                return [row for row in records if row['start'] >= began]
        def enough():
            rows = selected()
            return rows if len(rows) >= minimum else None
        rows = wait(enough, label + ' traffic window')
        ended = now()
        check(all(row['status'] in allowed for row in rows), f'{label}: unexpected responses {Counter(r["status"] for r in rows)}')
        check(all(row['backend'] not in excluded for row in rows), label + ': routed to excluded backend')
        duration = sorted(row['duration_seconds'] for row in rows)
        windows.append({'label': label, 'start': began, 'end': ended, 'count': len(rows),
                        'responses_per_second': len(rows) / (ended - began),
                        'p95_seconds': duration[math.ceil(0.95 * len(duration)) - 1],
                        'p99_seconds': duration[math.ceil(0.99 * len(duration)) - 1],
                        'statuses': dict(Counter(str(row['status']) for row in rows)),
                        'backend_counts': dict(Counter(row['backend'] for row in rows if row['backend']))})
        event('window_completed', label=label, count=len(rows))

    def crash(names, label):
        injected = event('fault_injected', scenario=label, action='kill', backends=names)
        for name in names:
            planned_exits[active[name]] = -signal.SIGKILL
            active[name].process.kill()  # Only Popen objects created by this harness.
        for name in names:
            reap(active.pop(name), -signal.SIGKILL, label)
        wait(lambda: health(names, 0), label + ' exclusion')
        for name in names:
            transition(name, 'UNHEALTHY', injected)
        # Summarize completed requests whose start is inside the measured
        # injection-to-observed-exclusion window, including late completions later.
        observations.append({'scenario': label, 'injection_seconds': injected['elapsed_seconds'],
                             'exclusion_observed_seconds': now(), 'backends': names})
        return injected

    def restore(names, label):
        injected = event('fault_restored', scenario=label, backends=names)
        for name in names:
            start_backend(name)
        wait(lambda: health(names, 1), label + ' recovery')
        for name in names:
            transition(name, 'HEALTHY', injected)

    def mode(name):
        injected = event('fault_injected' if name != 'normal' else 'fault_restored', action='mode', backend='C', mode=name)
        check(request(ports['C'], '/admin/mode?value=' + name, 'POST')[0] == 200, 'Fault control rejected')
        return injected

    def drive(worker):
        sequence = 0
        while not stop.is_set():
            began = now()
            status, identity, error, response_id = 0, None, None, None
            request_id = f'{plan["seed"]}-{worker}-{sequence}'
            try:
                status, body = request(proxy_port, plan['path'], request_id=request_id)
                if status == 200:
                    payload = json.loads(body)
                    identity, response_id = payload['server_id'], payload['request_id']
                    if response_id != request_id:
                        error = 'ResponseCorrelationMismatch'
            except (OSError, http.client.HTTPException, ValueError, KeyError) as failure:
                error = type(failure).__name__
            row = {'worker': worker, 'sequence': sequence, 'request_id': request_id, 'response_request_id': response_id,
                   'start': began, 'end': now(), 'duration_seconds': now() - began,
                   'status': status, 'backend': identity, 'error': error}
            with lock:
                records.append(row)
            sequence += 1
            stop.wait(0.005)

    try:
        event('plan', plan=plan)
        for name in 'ABC':
            start_backend(name)
        flags = ['--port', '0', '--metrics-port', '0', '--workers', '4', '--health-interval-ms', '40',
                 '--health-connect-timeout-ms', '80', '--health-response-timeout-ms', '100',
                 '--upstream-timeout-ms', '250', '--shutdown-grace-ms', '1000']
        for name in 'ABC':
            flags += ['--backend', f'{name},127.0.0.1,{ports[name]}']
        balancer, proxy_port = start(args.proxy, flags, 'chaos-proxy')
        check(balancer.event['eligible'] == 3, 'All-healthy bootstrap')
        for worker in range(plan['workers']):
            thread = threading.Thread(target=drive, args=(worker,), daemon=True)
            thread.start()
            threads.append(thread)
        window('control-before')
        report['checks'].append('CHAOS-01 healthy control')

        victim = plan['single_crash']
        wait(lambda: value(scrape('before_crash'), 'lb_inflight_requests') > 0, 'Requests active before crash')
        crash([victim], 'single-crash')
        window('single-excluded', excluded=[victim])
        restore([victim], 'single-crash')
        window('single-recovered')
        report['checks'].append('CHAOS-02 single crash and recovery')

        crash(plan['multi_crash'], 'multi-crash')
        window('multi-excluded', excluded=plan['multi_crash'])
        restore(plan['multi_crash'], 'multi-crash')
        window('multi-recovered')
        report['checks'].append('CHAOS-03 simultaneous multiple crashes')

        crash(plan['all_crash'], 'all-unavailable')
        window('all-excluded', allowed={503})
        restore(plan['all_crash'], 'all-unavailable')
        window('all-recovered')
        report['checks'].append('CHAOS-04 consistent 503 after all excluded')

        for fault in plan['fault_order']:
            before = scrape('before_' + fault)
            injected = mode(fault)
            code = {'delay': 504, 'reset': 502, 'error': 500}[fault]
            wait(lambda: any(row['status'] == code and row['start'] >= injected['elapsed_seconds']
                             for row in list(records)), fault + ' visible to clients')
            window(fault + '-during', allowed={200, code}, minimum=20)
            after = scrape(fault)
            check(value(after, 'lb_backend_healthy', backend='C') == 1, 'Business faults changed active readiness')
            if fault != 'error':
                reason = 'timeout' if fault == 'delay' else 'reset'
                check(value(after, 'lb_upstream_errors_total', backend='C', reason=reason) >
                      value(before, 'lb_upstream_errors_total', backend='C', reason=reason), 'Missing failure reason metric')
            mode('normal')
            window(fault + '-after')
        report['checks'].append('CHAOS-05 delay/reset/false-positive readiness')

        injected = mode('unready')
        wait(lambda: health(['C'], 0), 'False-negative readiness exclusion')
        transition('C', 'UNHEALTHY', injected)
        check(request(ports['C'])[0] == 200, 'Readiness controls business endpoint')
        window('false-readiness', excluded=['C'])
        injected = mode('normal')
        wait(lambda: health(['C'], 1), 'False-negative readiness recovery')
        transition('C', 'HEALTHY', injected)
        report['checks'].append('CHAOS-06 false-negative readiness')

        before = scrape('before_flap')
        mode('flap')
        wait(lambda: value(scrape('flap_poll'), 'lb_healthcheck_total', backend='C', result='failure') >=
             value(before, 'lb_healthcheck_total', backend='C', result='failure') + 5, 'Five alternating failed probes')
        after = scrape('after_flap')
        check(value(after, 'lb_backend_state_changes_total', backend='C', to_state='unhealthy') ==
              value(before, 'lb_backend_state_changes_total', backend='C', to_state='unhealthy'), 'Flapping caused state churn')
        mode('normal')
        window('flap-after')
        report['checks'].append('CHAOS-07 alternating readiness hysteresis')

        for index, name in enumerate(plan['restarts']):
            wait(lambda: value(scrape('restart_inflight'), 'lb_inflight_requests') > 0, 'No in-flight restart traffic')
            crash([name], f'restart-{index}')
            window(f'restart-{index}-excluded', excluded=[name], minimum=8)
            restore([name], f'restart-{index}')
        window('control-after', minimum=24)
        report['checks'].append('CHAOS-08 repeated restarts under traffic and final recovery')
        final = scrape('final')
        check(all(value(final, 'lb_backend_healthy', backend=name) == 1 for name in 'ABC'), 'Final recovery incomplete')
        check(balancer.process.poll() is None, 'Load balancer did not survive')
        if interruption_requested[0]:
            raise InterruptedError('Chaos harness received SIGTERM')
        report['passed'] = True
    except BaseException as error:
        report['failure'] = f'{type(error).__name__}: {error}'
        event('failure', message=report['failure'])
        raise
    finally:
        stop.set()
        for thread in threads:
            thread.join(timeout=4)
        cleanup_errors = ['Traffic worker did not stop' for thread in threads if thread.is_alive()]
        for child in reversed(list(owned)):
            try:
                expected = planned_exits.get(child, 0)
                if child.process.poll() is None:
                    if expected == -signal.SIGKILL:
                        child.process.kill()
                    else:
                        child.process.terminate()
                reap(child, expected, 'cleanup')
            except BaseException as error:
                cleanup_errors.append(str(error))
                if child.process.poll() is None:
                    child.process.kill()
                    child.process.wait(timeout=5)
                child.stderr.close()
                child.process.stdout.close()
        if cleanup_errors:
            report['cleanup_errors'] = cleanup_errors
            report['passed'] = False
        report['duration_seconds'] = now()
        report['request_count'] = len(records)
        report['status_counts'] = dict(Counter(str(row['status']) for row in records))
        for observation in observations:
            if 'exclusion_observed_seconds' in observation:
                began, ended = observation['injection_seconds'], observation['exclusion_observed_seconds']
                rows = [row for row in records if began <= row['end'] < ended]
                durations = sorted(row['duration_seconds'] for row in rows)
                observation['detection_window_requests'] = len(rows)
                observation['detection_window_failures'] = sum(row['status'] != 200 for row in rows)
                observation['detection_window_statuses'] = dict(Counter(str(row['status']) for row in rows))
                observation['responses_per_second'] = len(rows) / (ended - began)
                observation['p95_seconds'] = durations[math.ceil(.95 * len(durations)) - 1] if durations else None
                observation['p99_seconds'] = durations[math.ceil(.99 * len(durations)) - 1] if durations else None
                started_inside = [row for row in records if began <= row['start'] < ended]
                observation['requests_started_during_detection'] = len(started_inside)
                observation['failures_started_during_detection'] = sum(row['status'] != 200 for row in started_inside)
        bad = [row for row in records if row['error'] or row['status'] not in {200, 500, 502, 503, 504}
               or row['duration_seconds'] > 4 or row['status'] == 200 and row['backend'] not in {'A', 'B', 'C'}]
        if bad:
            report['invalid_responses'] = bad
            report['passed'] = False
        (args.logs / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
        with (args.logs / 'requests.jsonl').open('w') as output:
            for row in records:
                output.write(json.dumps(row) + '\n')
        with (args.logs / 'metrics.jsonl').open('w') as output:
            for sample in metrics:
                output.write(json.dumps(sample) + '\n')
        event_file.close()
        if report['passed']:
            print(json.dumps({'seed': plan['seed'], 'checks': report['checks'], 'requests': len(records),
                              'duration_seconds': report['duration_seconds']}))
        elif 'failure' not in report:
            raise AssertionError(f'Invalid responses or cleanup failures; see {args.logs / "report.json"}')


if __name__ == '__main__':
    main()
